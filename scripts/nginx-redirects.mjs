// Turns src/data/redirects.json into nginx `map` blocks: dist/_nginx/redirect-maps.conf.
// Runs as part of `npm run build`, so every build carries redirect rules that match its own pages, and
// the server's updater installs them (deploy/staging/update.py). The behaviour mirrors resolve() in
// scripts/verify-seo.mjs, which is the SEO check's model of the host:
//   query   old WordPress links with a query string (/sermons/?sermon_speaker=…), matched exactly
//   (search) /?s=… and /?q=… go to the search page, keeping the words searched for
//   exact   a missing page redirects to its new address
//   prefix  a missing page under an old address (event dates, feeds…) redirects; the longest prefix wins
// Rewrites (feeds served without a redirect) and the trailing-slash redirect live in
// deploy/nginx/savinggrace-site.conf, because they are fixed.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const redirects = JSON.parse(readFileSync(join(ROOT, "src/data/redirects.json"), "utf8"));
const decode = (p) => { try { return decodeURIComponent(p); } catch { return p; } };
/** An nginx string in double quotes; a $ would start a variable, so it is refused rather than guessed. */
const q = (s) => {
  if (/[$"\\\n]/u.test(s)) throw new Error(`Unsafe character in redirect: ${s}`);
  return `"${s}"`;
};
const regexEscape = (s) => s.replace(/[.*+?^${}()|[\]\\]/gu, "\\$&");

const query = redirects.filter((r) => r.match === "query");
const exact = redirects.filter((r) => r.match === "exact");
const prefix = redirects.filter((r) => r.match === "prefix").sort((a, b) => b.from.length - a.from.length);

const lines = [
  "# Generated by scripts/nginx-redirects.mjs from src/data/redirects.json. Do not edit by hand.",
  `# ${query.length} query, ${exact.length} exact and ${prefix.length} prefix redirects.`,
  "map_hash_bucket_size 256;",
  "map_hash_max_size 16384;",
  "",
  "# Old WordPress links with a query string, matched on the address exactly as requested.",
  "map $request_uri $sg_query_redirect {",
  "  default \"\";",
];
const seen = new Set();
const addKey = (key, to) => { if (!seen.has(key)) { seen.add(key); lines.push(`  ${q(key)} ${q(to)};`); } };
for (const r of query) {
  addKey(r.from, r.to);
  addKey(decode(r.from), r.to);
}
lines.push("  # WordPress search links: /?s=words or /?q=words, keeping the words.", "  \"~^/\\?(?:s|q)=\" \"/search/?$args\";", "}", "");

lines.push("# Pages that moved: applies only when no file exists at the address ($uri is already decoded).", "map $uri $sg_exact_redirect {", "  default \"\";");
for (const r of exact) lines.push(`  ${q(decode(r.from))} ${q(r.to)};`);
lines.push("}", "");

lines.push("# Everything under an old address: applies only when no file exists; the longest prefix is listed first.", "map $uri $sg_prefix_redirect {", "  default \"\";");
for (const r of prefix) lines.push(`  ${q(`~^${regexEscape(decode(r.from))}`)} ${q(r.to)};`);
lines.push("}", "");

const out = join(ROOT, "dist", "_nginx", "redirect-maps.conf");
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, `${lines.join("\n")}\n`);
console.log(`nginx redirect maps: ${query.length} query, ${exact.length} exact, ${prefix.length} prefix -> dist/_nginx/redirect-maps.conf`);
